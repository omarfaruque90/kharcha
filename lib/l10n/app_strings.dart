  static String get(String key, String lang) {
    // Lookup order: per-language partial map (16 world languages, ~80 keys
    // each) → full in-file map (en/bn/hi/ur/ar) → English → raw key.
    //
    // Lean-startup note: the 16 world-language maps are NOT merged into
    // `_values` at startup. Each is a `const` map in its own file; the
    // switch below only touches the one map matching the active language,
    // so there is no extra allocation or merge cost on app launch.
    return _worldLangMap(lang)[key] ??
        _values[lang]?[key] ??
        _values['en']![key] ??
        key;
  }

  /// Returns the partial (~80-key) map for one of the 16 world languages,
  /// or an empty map for any other language code.
  static Map<String, String> _worldLangMap(String lang) {
    switch (lang) {
      case 'es':
        return langEs;
      case 'fr':
        return langFr;
      case 'de':
        return langDe;
      case 'pt':
        return langPt;
      case 'ru':
        return langRu;
      case 'zh':
        return langZh;
      case 'ja':
        return langJa;
      case 'ko':
        return langKo;
      case 'tr':
        return langTr;
      case 'id':
        return langId;
      case 'ms':
        return langMs;
      case 'vi':
        return langVi;
      case 'th':
        return langTh;
      case 'it':
        return langIt;
      case 'fa':
        return langFa;
      case 'nl':
        return langNl;
      default:
        return const {};
    }
  }

